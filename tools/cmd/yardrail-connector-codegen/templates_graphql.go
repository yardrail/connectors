// goStringLiteral quotes s as a Go string literal, as a raw string when s has
// no backquote so operation text stays readable in generated code.
func goStringLiteral(s string) string {
	if !strings.Contains(s, "`") {
		return "`" + s + "`"
	}

	return strconv.Quote(s)
}

