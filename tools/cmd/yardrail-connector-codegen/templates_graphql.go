// call POSTs the operation with inputs as its variables and returns the
// response's data. Any entry in errors fails the call, even alongside data.
func (e *endpoint) call(ctx context.Context, function, query string, inputs json.RawMessage) (any, error) {
	reqBody, err := json.Marshal(graphqlRequest{Query: query, Variables: inputs})
	if err != nil {
		return nil, fmt.Errorf("{{.ConnectorID}}.%s: encoding request: %w", function, err)
	}

	req, err := http.NewRequestWithContext(ctx, http.MethodPost, e.url, bytes.NewReader(reqBody))
	if err != nil {
		return nil, fmt.Errorf("{{.ConnectorID}}.%s: %w", function, err)
	}

	req.Header.Set("Content-Type", "application/json")

	if err := e.auth(ctx, req); err != nil {
		return nil, fmt.Errorf("{{.ConnectorID}}.%s: auth: %w", function, err)
	}

	cl := e.httpClient
	if cl == nil {
		cl = http.DefaultClient
	}

	resp, err := cl.Do(req)
	if err != nil {
		return nil, fmt.Errorf("{{.ConnectorID}}.%s: %w", function, err)
	}

	if resp == nil {
		return nil, fmt.Errorf("{{.ConnectorID}}.%s: nil response", function)
	}

	respBody, readErr := io.ReadAll(resp.Body)
	closeErr := resp.Body.Close()

	if readErr != nil {
		return nil, fmt.Errorf("{{.ConnectorID}}.%s: reading response: %w", function, readErr)
	}

	if closeErr != nil {
		return nil, fmt.Errorf("{{.ConnectorID}}.%s: closing response: %w", function, closeErr)
	}

	if resp.StatusCode >= 400 {
		return nil, fmt.Errorf("{{.ConnectorID}}.%s: HTTP %d: %s", function, resp.StatusCode, string(respBody))
	}

	var out graphqlResponse
	if err := json.Unmarshal(respBody, &out); err != nil {
		return nil, fmt.Errorf("{{.ConnectorID}}.%s: decoding response: %w", function, err)
	}

	if len(out.Errors) > 0 {
		msgs := make([]string, 0, len(out.Errors))
		for _, ge := range out.Errors {
			msgs = append(msgs, ge.Message)
		}

		return nil, fmt.Errorf("%w: {{.ConnectorID}}.%s: %s", errGraphQL, function, strings.Join(msgs, "; "))
	}

	return out.Data, nil
}
