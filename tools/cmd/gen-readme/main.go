// Command gen-readme renders README.md from README.md.tmpl, filling in
// connector metadata scraped from manifests, go.mod files, generated MCP
// tools, and vacuum spectral reports.
package main

import (
	"bytes"
	"encoding/json"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"slices"
	"strconv"
	"strings"
	"text/template"

	"gopkg.in/yaml.v3"
)

type manifest struct {
	Connector struct {
		ID          string `yaml:"id"`
		Name        string `yaml:"name"`
		Description string `yaml:"description"`
	} `yaml:"connector"`
}

type spectralEntry struct {
	Code     string `json:"code"`
	Severity int    `json:"severity"`
}

type connectorInfo struct {
	Path                string
	Module              string
	Name                string
	Description         string
	Tools               int
	MissingOpDesc       int
	MissingParamDesc    int
	MissingCompDesc     int
	HasSpec             bool
	HasClient           bool
	HasMCP              bool
}

type templateData struct {
	Connectors []connectorInfo
}

const (
	templateRelPath = "tools/cmd/gen-readme/README.md.tmpl"
	outputFileMode  = 0o644

	generatedWarning = `<!--
This file is generated by tools/cmd/gen-readme from ` + templateRelPath + `.
Edit that template, then run ` + "`task docs:readme`" + ` to regenerate this file.
Do not hand-edit README.md directly.
-->
`
)

func main() {
	if err := run(); err != nil {
		fmt.Fprintln(os.Stderr, "gen-readme:", err)
		os.Exit(1)
	}
}

func run() error {
	root, err := repoRoot()
	if err != nil {
		return fmt.Errorf("locating repo root: %w", err)
	}

	connectors, err := discoverConnectors(root)
	if err != nil {
		return fmt.Errorf("discovering connectors: %w", err)
	}

	tmplPath := filepath.Join(root, templateRelPath)
	funcMap := template.FuncMap{
		"pad": func(s string, width int) string {
			if len(s) >= width {
				return s
			}
			return s + strings.Repeat(" ", width-len(s))
		},
		"padr": func(n int, width int) string {
			s := strconv.Itoa(n)
			if len(s) >= width {
				return s
			}
			return s + strings.Repeat(" ", width-len(s))
		},
		"dash": func(n int) string {
			if n == 0 {
				return "—"
			}
			return strconv.Itoa(n)
		},
		"descTriple": func(op, param, comp int) string {
			if op == 0 && param == 0 && comp == 0 {
				return "—"
			}
			return strconv.Itoa(op) + " / " + strconv.Itoa(param) + " / " + strconv.Itoa(comp)
		},
	}

	tmpl, err := template.New(filepath.Base(tmplPath)).Funcs(funcMap).ParseFiles(tmplPath)
	if err != nil {
		return fmt.Errorf("parsing %s: %w", tmplPath, err)
	}

	var out bytes.Buffer
	if err := tmpl.Execute(&out, templateData{Connectors: connectors}); err != nil {
		return fmt.Errorf("rendering template: %w", err)
	}

	outPath := filepath.Join(root, "README.md")
	if err := os.WriteFile(outPath, withGeneratedWarning(out.Bytes()), outputFileMode); err != nil {
		return fmt.Errorf("writing %s: %w", outPath, err)
	}

	fmt.Println("wrote", outPath)
	return nil
}

func withGeneratedWarning(rendered []byte) []byte {
	title, body, found := bytes.Cut(rendered, []byte("\n"))
	if !found {
		return rendered
	}
	return []byte(string(title) + "\n\n" + generatedWarning + string(body))
}

func repoRoot() (string, error) {
	out, err := exec.Command("git", "rev-parse", "--show-toplevel").Output()
	if err != nil {
		return "", err
	}
	return strings.TrimSpace(string(out)), nil
}

func discoverConnectors(root string) ([]connectorInfo, error) {
	var connectors []connectorInfo

	manifests, err := filepath.Glob(filepath.Join(root, "*", "*", "manifest.yaml"))
	if err != nil {
		return nil, err
	}
	deeper, err := filepath.Glob(filepath.Join(root, "*", "*", "*", "manifest.yaml"))
	if err != nil {
		return nil, err
	}
	manifests = append(manifests, deeper...)

	// Also discover modules without manifests (e.g. monday)
	goMods, err := filepath.Glob(filepath.Join(root, "*", "*", "go.mod"))
	if err != nil {
		return nil, err
	}
	deeperMods, err := filepath.Glob(filepath.Join(root, "*", "*", "*", "go.mod"))
	if err != nil {
		return nil, err
	}
	goMods = append(goMods, deeperMods...)

	seen := make(map[string]bool)

	for _, mPath := range manifests {
		dir := filepath.Dir(mPath)
		relPath, _ := filepath.Rel(root, dir)
		seen[relPath] = true

		c, err := loadConnector(root, dir, relPath, mPath)
		if err != nil {
			return nil, fmt.Errorf("loading %s: %w", relPath, err)
		}
		connectors = append(connectors, c)
	}

	for _, modPath := range goMods {
		dir := filepath.Dir(modPath)
		relPath, _ := filepath.Rel(root, dir)

		if seen[relPath] || relPath == "tools" || strings.HasPrefix(relPath, "tools/") || strings.HasPrefix(relPath, "scripts/") || strings.HasSuffix(relPath, "/tools") || strings.Contains(relPath, "/tools/") {
			continue
		}
		if _, err := os.Stat(filepath.Join(dir, "manifest.yaml")); err == nil {
			continue
		}
		seen[relPath] = true

		c, err := loadConnector(root, dir, relPath, "")
		if err != nil {
			return nil, fmt.Errorf("loading %s: %w", relPath, err)
		}
		connectors = append(connectors, c)
	}

	slices.SortFunc(connectors, func(a, b connectorInfo) int {
		return strings.Compare(a.Path, b.Path)
	})

	return connectors, nil
}

func loadConnector(root, dir, relPath, manifestPath string) (connectorInfo, error) {
	c := connectorInfo{Path: relPath}

	// Module path from go.mod
	modData, err := os.ReadFile(filepath.Join(dir, "go.mod"))
	if err == nil {
		for _, line := range strings.Split(string(modData), "\n") {
			if strings.HasPrefix(line, "module ") {
				c.Module = strings.TrimPrefix(line, "module ")
				break
			}
		}
	}

	// Manifest
	if manifestPath != "" {
		data, err := os.ReadFile(manifestPath)
		if err != nil {
			return c, err
		}
		var m manifest
		if err := yaml.Unmarshal(data, &m); err != nil {
			return c, err
		}
		c.Name = m.Connector.Name
		c.Description = m.Connector.Description
	} else {
		// Derive name from the path's top directory (the vendor)
		c.Name = strings.Split(relPath, "/")[0]
	}

	// Check for spec/client/mcp
	if _, err := os.Stat(filepath.Join(dir, "spec")); err == nil {
		c.HasSpec = true
	}
	if _, err := os.Stat(filepath.Join(dir, "client")); err == nil {
		c.HasClient = true
	}
	if _, err := os.Stat(filepath.Join(dir, "mcp")); err == nil {
		c.HasMCP = true
	}

	// Tool count from tools_gen.go
	toolsGen := filepath.Join(dir, "mcp", "tools_gen.go")
	if data, err := os.ReadFile(toolsGen); err == nil {
		c.Tools = strings.Count(string(data), "s.AddTool(")
	}

	// Vacuum spectral report for missing descriptions
	specPath := filepath.Join(dir, "spec", "openapi.json")
	if _, err := os.Stat(specPath); err == nil {
		c.MissingOpDesc, c.MissingParamDesc, c.MissingCompDesc = vacuumDescriptions(specPath)
	}

	return c, nil
}

func vacuumDescriptions(specPath string) (opDesc, paramDesc, compDesc int) {
	cmd := exec.Command("vacuum", "spectral-report", "-o", "-n", specPath)
	out, err := cmd.Output()
	if err != nil {
		return 0, 0, 0
	}

	var entries []spectralEntry
	if err := json.Unmarshal(out, &entries); err != nil {
		return 0, 0, 0
	}

	for _, e := range entries {
		switch e.Code {
		case "operation-description":
			opDesc++
		case "oas3-parameter-description":
			paramDesc++
		case "component-description":
			compDesc++
		}
	}

	return opDesc, paramDesc, compDesc
}
